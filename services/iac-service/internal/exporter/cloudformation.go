// ExportCloudFormation generates AWS CloudFormation YAML from a CTM graph
func ExportCloudFormation(graph model.Graph, region string) *model.ExportResponse {
	var sb strings.Builder

	sb.WriteString("AWSTemplateFormatVersion: \"2010-09-09\"\n")
	sb.WriteString(fmt.Sprintf("Description: Infrastructure topology - auto-generated by Moktopus (region: %s)\n\n", region))
	sb.WriteString("Resources:\n")

	for _, node := range graph.Nodes {
		sb.WriteString(generateCFResource(node))
	}

	content := sb.String()
	return &model.ExportResponse{
		Format:  "cloudformation",
		Content: content,
		Files: []model.File{
			{Name: "template.yaml", Content: content},
		},
	}
}

func generateCFResource(node model.Node) string {
	name := cfLogicalName(node.ID)

	switch node.Type {
	case "service", "worker":
		replicas := getConfigInt(node.Config, "replicas", 2)
		return fmt.Sprintf(`  %s:
    Type: AWS::ECS::Service
    Properties:
      ServiceName: %s
      Cluster: !Ref ECSCluster
      DesiredCount: %d
      LaunchType: FARGATE
      NetworkConfiguration:
        AwsvpcConfiguration:
          Subnets: !Ref PrivateSubnets
          SecurityGroups:
            - !Ref ServiceSecurityGroup

`, name, node.ID, replicas)

	case "database":
		engine := getConfigString(node.Config, "engine", "postgres")
		instanceClass := getConfigString(node.Config, "instanceClass", "db.t4g.medium")
		return fmt.Sprintf(`  %s:
    Type: AWS::RDS::DBInstance
    Properties:
      DBInstanceIdentifier: %s
      Engine: %s
      EngineVersion: "16"
      DBInstanceClass: %s
      AllocatedStorage: 20
      StorageType: gp3
      MultiAZ: true
      MasterUsername: admin
      MasterUserPassword: !Ref DBPassword
      VPCSecurityGroups:
        - !Ref DBSecurityGroup

`, name, node.ID, engine, instanceClass)

	case "cache":
		nodeType := getConfigString(node.Config, "nodeType", "cache.t4g.medium")
		return fmt.Sprintf(`  %s:
    Type: AWS::ElastiCache::ReplicationGroup
    Properties:
      ReplicationGroupDescription: %s cache cluster
      Engine: redis
      EngineVersion: "7.1"
      CacheNodeType: %s
      NumCacheClusters: 2
      AutomaticFailoverEnabled: true

`, name, node.ID, nodeType)

	case "queue":
		return fmt.Sprintf(`  %s:
    Type: AWS::SQS::Queue
    Properties:
      QueueName: %s
      VisibilityTimeout: 30
      MessageRetentionPeriod: 345600

`, name, node.ID)

	case "load-balancer":
		return fmt.Sprintf(`  %s:
    Type: AWS::ElasticLoadBalancingV2::LoadBalancer
    Properties:
      Name: %s
      Type: application
      Scheme: internet-facing
      Subnets: !Ref PublicSubnets
      SecurityGroups:
        - !Ref ALBSecurityGroup

`, name, node.ID)

	case "api-gateway":
		return fmt.Sprintf(`  %s:
    Type: AWS::ApiGatewayV2::Api
    Properties:
      Name: %s
      ProtocolType: HTTP
      Description: API Gateway endpoint

`, name, node.ID)

	case "object-store", "storage":
		return fmt.Sprintf(`  %s:
    Type: AWS::S3::Bucket
    Properties:
      BucketName: %s
      VersioningConfiguration:
        Status: Enabled

`, name, node.ID)

	case "cdn":
		return fmt.Sprintf(`  %s:
    Type: AWS::CloudFront::Distribution
    Properties:
      DistributionConfig:
        Enabled: true
        DefaultCacheBehavior:
          ViewerProtocolPolicy: redirect-to-https
          TargetOriginId: %s-origin
          ForwardedValues:
            QueryString: false
        Origins:
          - Id: %s-origin
            DomainName: origin.example.com
            CustomOriginConfig:
              HTTPPort: 80
              OriginProtocolPolicy: http-only

`, name, node.ID, node.ID)

	case "serverless", "lambda", "function":
		return fmt.Sprintf(`  %s:
    Type: AWS::Lambda::Function
    Properties:
      FunctionName: %s
      Runtime: nodejs18.x
      Handler: index.handler
      MemorySize: 256
      Timeout: 30
      Role: !GetAtt LambdaExecutionRole.Arn

`, name, node.ID)

	case "dns":
		return fmt.Sprintf(`  %s:
    Type: AWS::Route53::HostedZone
    Properties:
      Name: %s.example.com

`, name, node.ID)

	case "firewall", "waf":
		return fmt.Sprintf(`  %s:
    Type: AWS::WAFv2::WebACL
    Properties:
      Name: %s
      Scope: REGIONAL
      DefaultAction:
        Allow: {}
      VisibilityConfig:
        SampledRequestsEnabled: true
        CloudWatchMetricsEnabled: true
        MetricName: %s

`, name, node.ID, node.ID)

	case "notification", "sns", "pubsub":
		return fmt.Sprintf(`  %s:
    Type: AWS::SNS::Topic
    Properties:
      TopicName: %s

`, name, node.ID)

	case "container", "kubernetes", "k8s":
		return fmt.Sprintf(`  %s:
    Type: AWS::EKS::Cluster
    Properties:
      Name: %s
      RoleArn: !GetAtt EKSRole.Arn
      ResourcesVpcConfig:
        SubnetIds: !Ref PrivateSubnets

`, name, node.ID)

	case "vpn":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::VPNGateway
    Properties:
      Type: ipsec.1
      Tags:
        - Key: Name
          Value: %s

`, name, node.ID)

	case "vpc":
		cidr := getConfigString(node.Config, "cidrBlock", "10.0.0.0/16")
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::VPC
    Properties:
      CidrBlock: %s
      EnableDnsSupport: true
      EnableDnsHostnames: true
      Tags:
        - Key: Name
          Value: %s

`, name, cidr, node.ID)

	case "subnet":
		cidr := getConfigString(node.Config, "cidrBlock", "10.0.1.0/24")
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::Subnet
    Properties:
      VpcId: !Ref VPC
      CidrBlock: %s
      AvailabilityZone: !Select [0, !GetAZs ""]
      Tags:
        - Key: Name
          Value: %s

`, name, cidr, node.ID)

	case "internet-gateway":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::InternetGateway
    Properties:
      Tags:
        - Key: Name
          Value: %s

`, name, node.ID)

	case "nat-gateway":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::NatGateway
    Properties:
      AllocationId: !GetAtt EIP.AllocationId
      SubnetId: !Ref PublicSubnet
      Tags:
        - Key: Name
          Value: %s

`, name, node.ID)

	case "security-group":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::SecurityGroup
    Properties:
      GroupDescription: Security group for %s
      VpcId: !Ref VPC
      SecurityGroupIngress:
        - IpProtocol: tcp
          FromPort: 443
          ToPort: 443
          CidrIp: 0.0.0.0/0
      SecurityGroupEgress:
        - IpProtocol: "-1"
          CidrIp: 0.0.0.0/0

`, name, node.ID)

	case "route-table":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::RouteTable
    Properties:
      VpcId: !Ref VPC
      Tags:
        - Key: Name
          Value: %s

`, name, node.ID)

	case "elastic-ip":
		return fmt.Sprintf(`  %s:
    Type: AWS::EC2::EIP
    Properties:
      Domain: vpc

`, name)

	case "stream":
		return fmt.Sprintf(`  %s:
    Type: AWS::Kinesis::Stream
    Properties:
      Name: %s
      ShardCount: 1
      RetentionPeriodHours: 24

`, name, node.ID)

	case "monitoring":
		return fmt.Sprintf(`  %s:
    Type: AWS::Logs::LogGroup
    Properties:
      LogGroupName: /app/%s
      RetentionInDays: 30

`, name, node.ID)

	case "iam":
		return fmt.Sprintf(`  %s:
    Type: AWS::IAM::Role
    Properties:
      RoleName: %s
      AssumeRolePolicyDocument:
        Version: "2012-10-17"
        Statement:
          - Effect: Allow
            Principal:
              Service: ecs-tasks.amazonaws.com
            Action: sts:AssumeRole

`, name, node.ID)

	default:
		// Fallback: generate a generic ECS service rather than manual mapping
		replicas := getConfigInt(node.Config, "replicas", 1)
		return fmt.Sprintf(`  %s:
    Type: AWS::ECS::Service
    Properties:
      ServiceName: %s
      Cluster: !Ref ECSCluster
      DesiredCount: %d
      LaunchType: FARGATE

`, name, node.ID, replicas)
	}
}

func cfLogicalName(id string) string {
	parts := strings.Split(id, "-")
	var result strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			result.WriteString(strings.ToUpper(p[:1]))
			if len(p) > 1 {
				result.WriteString(p[1:])
			}
		}
	}
	return result.String()
}

func getConfigInt(config map[string]interface{}, key string, defaultVal int) int {
	if config == nil {
		return defaultVal
	}
	v, ok := config[key]
	if !ok {
		return defaultVal
	}
	switch val := v.(type) {
	case float64:
		return int(val)
	case int:
		return val
	default:
		return defaultVal
	}
}
